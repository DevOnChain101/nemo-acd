#!/usr/bin/env python3
"""Generates crates/synthesis-tui-render/src/logo_art.rs (braille art of the brand symbol) offline.

Python standard library only (zlib decodes the PNG). Usage, from the repository root:
    python3 tools/logo-art/gen.py [--png PATH] [--out PATH] [--preview]
The Rust table is committed; nothing is decoded at runtime. The source is
design/01-brand/logo/png/synthesis-symbol-transparent-512.png (8-bit RGBA, not interlaced).
"""
import argparse
import struct
import sys
import zlib

COLS, ROWS = 16, 8            # cells; a braille cell is 2x4 dots, so 32x32 dots: square on a 1:2 cell
DW, DH = COLS * 2, ROWS * 4
SHADES = 8                    # per-cell lightness levels, 0 (dark) to 7 (light)
# braille dot bit for (dx, dy) inside a cell; a dot is on where the symbol is opaque
BIT = {(0, 0): 0x01, (0, 1): 0x02, (0, 2): 0x04, (1, 0): 0x08, (1, 1): 0x10, (1, 2): 0x20, (0, 3): 0x40, (1, 3): 0x80}


def read_png(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat, hdr = 8, b"", None
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
    w, h, depth, ctype, _, _, interlace = hdr
    assert (depth, ctype, interlace) == (8, 6, 0), "need 8-bit RGBA, not interlaced"
    raw, stride, bpp = zlib.decompress(idat), w * 4, 4
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, rows


def sample(w, h, rows):
    """Crop to the opaque bounding box (square, centred) and average into DW x DH dots."""
    ys = [y for y in range(h) if any(rows[y][x * 4 + 3] > 127 for x in range(w))]
    xs = [x for x in range(w) if any(rows[y][x * 4 + 3] > 127 for y in ys)]
    x0, x1, y0, y1 = min(xs), max(xs) + 1, min(ys), max(ys) + 1
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    ox, oy = cx - side / 2, cy - side / 2
    dots = []
    for j in range(DH):
        row = []
        for i in range(DW):
            xa, xb = int(ox + side * i / DW), int(ox + side * (i + 1) / DW)
            ya, yb = int(oy + side * j / DH), int(oy + side * (j + 1) / DH)
            n = a = lum = 0
            for y in range(max(ya, 0), min(max(yb, ya + 1), h)):
                for x in range(max(xa, 0), min(max(xb, xa + 1), w)):
                    px = rows[y][x * 4:x * 4 + 4]
                    n += 1
                    a += px[3]
                    lum += (0.2126 * px[0] + 0.7152 * px[1] + 0.0722 * px[2]) * px[3]
            alpha = a / (255 * n) if n else 0
            row.append((alpha, lum / a if a else 0))
        dots.append(row)
    return dots


def build(dots):
    art, shade = [], []
    for r in range(ROWS):
        line, sh = "", []
        for c in range(COLS):
            bits, lsum, lcount = 0, 0.0, 0
            for dy in range(4):
                for dx in range(2):
                    alpha, lum = dots[r * 4 + dy][c * 2 + dx]
                    if alpha < 0.5:
                        continue
                    lcount += 1
                    lsum += lum
                    bits |= BIT[(dx, dy)]
            line += chr(0x2800 + bits)
            sh.append(0 if not lcount else min(SHADES - 1, int(lsum / lcount / 256 * SHADES)))
        art.append(line)
        shade.append(sh)
    return art, shade


def rust(art, shade, png):
    out = [
        "//! Braille art of the brand symbol, generated by `tools/logo-art/gen.py` from",
        f"//! `{png}`. Do not edit: run the script again.",
        "//!",
        "//! `ART[row]` is one braille character per cell; `SHADE[row][col]` is the lightness of that",
        f"//! cell, 0 (dark) to {SHADES - 1} (light), which the welcome screen maps to a colour (sheen).",
        "",
        f"pub const COLS: usize = {COLS};",
        f"pub const ROWS: usize = {ROWS};",
        f"pub const SHADES: u8 = {SHADES};",
        "",
        f"pub const ART: [&str; {ROWS}] = [",
    ]
    out += [f'    "{l}",' for l in art]
    out += ["];", "", f"pub const SHADE: [[u8; {COLS}]; {ROWS}] = ["]
    out += ["    [" + ", ".join(str(v) for v in r) + "]," for r in shade]
    out += ["];", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png", default="design/01-brand/logo/png/synthesis-symbol-transparent-512.png")
    ap.add_argument("--out", default="crates/synthesis-tui-render/src/logo_art.rs")
    ap.add_argument("--preview", action="store_true", help="print the art instead of writing the file")
    a = ap.parse_args()
    art, shade = build(sample(*read_png(a.png)))
    if a.preview:
        print("\n".join(art))
        return
    open(a.out, "w").write(rust(art, shade, a.png))
    print("\n".join(art), file=sys.stderr)


if __name__ == "__main__":
    main()
